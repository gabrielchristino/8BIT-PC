`timescale 1ns/1ps
// Pin-derived logic. RC delay and external recovery resolution are conditional abstractions.
module schmitt_reset_netlist #(parameter TIMED=0,RESOLVE_LATE=1,parameter realtime ASSERT_DELAY=1000,RELEASE_DELAY=42000)(input wire raw_safe_n,backend_source,cpu_source,output wire bank_reset_n,cpu_reset_n,access_safe,bank_memory_n,bank_keyboard_n,bank_decode_n,safe_memory,safe_keyboard,cpu_core_clk,access_clk,keyboard_clk);
wire n_ACCESS_CLK;
wire n_ACCESS_SAFE;
wire n_ALL_READY;
wire n_BACKEND;
wire n_BACKEND_ROOT;
wire n_BANK_DECODE_N;
wire n_BANK_KEYBOARD_N;
wire n_BANK_MEMORY_N;
wire n_BANK_RESET_CLK;
wire n_BANK_RESET_N;
wire n_CPU_CLEAR_FAST_N;
wire n_CPU_CLK;
wire n_CPU_CORE_CLK;
wire n_CPU_RESET_CLK;
wire n_CPU_RESET_N;
wire n_CPU_SYNC1;
wire n_DELAY_CLEAR_N;
wire n_DELAY_INV;
wire n_DELAY_RC;
wire n_KEYBOARD_CLK;
wire n_RAW_BUFFERED;
wire n_RAW_INVERTED;
wire n_RAW_SAFE_N;
wire n_RESET_SYNC1;
wire n_SAFE_KEYBOARD;
wire n_SAFE_MEMORY;
wire n_SUPERVISOR_SENSE;
wire U3_unused_qb0,U3_unused_qb1,U5_unused_qb0,U5_unused_qb1;
assign n_RAW_SAFE_N=raw_safe_n;
assign n_BACKEND=backend_source;
assign n_CPU_CLK=cpu_source;
assign #(RELEASE_DELAY,ASSERT_DELAY) n_DELAY_RC=n_RAW_BUFFERED;
assign #(TIMED?10:0) n_SAFE_MEMORY=1'b0 ? 1'bz : n_ACCESS_SAFE;
assign #(TIMED?10:0) n_SAFE_KEYBOARD=1'b0 ? 1'bz : n_ACCESS_SAFE;
assign #(TIMED?10:0) n_BANK_DECODE_N=1'b0 ? 1'bz : n_BANK_MEMORY_N;
assign #(TIMED?12:0) n_DELAY_INV=~n_DELAY_RC;
assign #(TIMED?12:0) n_DELAY_CLEAR_N=~n_DELAY_INV;
assign #(TIMED?12:0) n_RAW_INVERTED=~n_RAW_SAFE_N;
assign #(TIMED?12:0) n_RAW_BUFFERED=~n_RAW_INVERTED;
net14b_ahc74 #(.TIMED(TIMED),.RESET_BOUNDARY(1),.FIRST_STAGE(1),.RESOLVE_LATE(RESOLVE_LATE)) U3_0(n_BANK_RESET_CLK,n_DELAY_CLEAR_N,1'b1,1'b1,n_RESET_SYNC1,U3_unused_qb0,1'b1);
net14b_ahc74 #(.TIMED(TIMED),.RESET_BOUNDARY(1),.FIRST_STAGE(0),.RESOLVE_LATE(RESOLVE_LATE)) U3_1(n_BANK_RESET_CLK,n_DELAY_CLEAR_N,1'b1,n_RESET_SYNC1,n_BANK_RESET_N,U3_unused_qb1,1'b1);
assign #(TIMED?10:0) n_ALL_READY=n_BANK_RESET_N & n_CPU_RESET_N;
assign #(TIMED?10:0) n_ACCESS_SAFE=n_RAW_BUFFERED & n_ALL_READY;
assign #(TIMED?10:0) n_CPU_CLEAR_FAST_N=n_RAW_BUFFERED & n_BANK_RESET_N;
net14b_ahc74 #(.TIMED(TIMED),.RESET_BOUNDARY(1),.FIRST_STAGE(1),.RESOLVE_LATE(RESOLVE_LATE)) U5_0(n_CPU_RESET_CLK,n_CPU_CLEAR_FAST_N,1'b1,1'b1,n_CPU_SYNC1,U5_unused_qb0,1'b1);
net14b_ahc74 #(.TIMED(TIMED),.RESET_BOUNDARY(1),.FIRST_STAGE(0),.RESOLVE_LATE(RESOLVE_LATE)) U5_1(n_CPU_RESET_CLK,n_CPU_CLEAR_FAST_N,1'b1,n_CPU_SYNC1,n_CPU_RESET_N,U5_unused_qb1,1'b1);
assign #(TIMED?10:0) n_BANK_MEMORY_N=1'b0 ? 1'bz : n_BANK_RESET_N;
assign #(TIMED?10:0) n_BANK_KEYBOARD_N=1'b0 ? 1'bz : n_BANK_RESET_N;
assign #(TIMED?10:0) n_CPU_CORE_CLK=1'b0 ? 1'bz : n_CPU_CLK;
assign #(TIMED?10:0) n_CPU_RESET_CLK=1'b0 ? 1'bz : n_CPU_CLK;
assign #(TIMED?10:0) n_BACKEND_ROOT=1'b0 ? 1'bz : n_BACKEND;
assign #(TIMED?10:0) n_ACCESS_CLK=1'b0 ? 1'bz : n_BACKEND_ROOT;
assign #(TIMED?10:0) n_KEYBOARD_CLK=1'b0 ? 1'bz : n_BACKEND_ROOT;
assign #(TIMED?10:0) n_BANK_RESET_CLK=1'b0 ? 1'bz : n_BACKEND_ROOT;
assign bank_reset_n=n_BANK_RESET_N;
assign cpu_reset_n=n_CPU_RESET_N;
assign access_safe=n_ACCESS_SAFE;
assign bank_memory_n=n_BANK_MEMORY_N;
assign bank_keyboard_n=n_BANK_KEYBOARD_N;
assign bank_decode_n=n_BANK_DECODE_N;
assign safe_memory=n_SAFE_MEMORY;
assign safe_keyboard=n_SAFE_KEYBOARD;
assign cpu_core_clk=n_CPU_CORE_CLK;
assign access_clk=n_ACCESS_CLK;
assign keyboard_clk=n_KEYBOARD_CLK;
endmodule
