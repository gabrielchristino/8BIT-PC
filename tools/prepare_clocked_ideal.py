"""Repair the unparameterized ideal module token; freeze timed runner inputs."""
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def main():
    source=ROOT/'tools/run_clocked_vectors.py'
    text=source.read_text()
    old="text = text.replace('isa1_memory #', 'isa1_clocked_memory #')"
    assert text.count(old)==1
    text=text.replace(old,"text = text.replace('isa1_memory ', 'isa1_clocked_memory ')")
    text=text.replace("'tools/run_clocked_vectors.py', 'tools/prepare_clocked_vectors.py'",
                      "'tools/run_clocked_vectors_ideal.py', 'tools/prepare_clocked_vectors.py', 'tools/prepare_clocked_ideal.py'")
    assert "'tools/run_clocked_vectors_ideal.py'" in text
    destination=ROOT/'tools/run_clocked_vectors_ideal.py'
    destination.write_text('# GENERATED by prepare_clocked_ideal.py; timed tested runner unchanged.\n'+text)
    paths=[Path(__file__),source,destination]
    (ROOT/'verification/net23/ideal-adapter-origin.json').write_text(json.dumps({'date':'2026-11-26',
        'transformation':'Broaden module identifier replacement to cover ideal instantiation without #parameters. Timed runner and all shared circuit/model files unchanged; canonical ideal report is produced by separate corrected runner.',
        'files':[{'path':p.relative_to(ROOT).as_posix(),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in paths]},indent=2)+'\n')


if __name__=='__main__':main()
