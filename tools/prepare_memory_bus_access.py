"""Derive a separate NET-13 controller with registered write-driver window."""
import hashlib
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]


def once(s,old,new):
    if s.count(old)!=1:raise ValueError('Unexpected base '+old[:70])
    return s.replace(old,new)


def main():
    base=ROOT/'tools/build_memory_access.py';s=base.read_text()
    s=once(s,"OUT=ROOT/'hardware/memory_access'","OUT=ROOT/'hardware/memory_bus_access'")
    s=once(s,"VERIFY=ROOT/'verification/net12'","VERIFY=ROOT/'verification/net13/access'")
    s=once(s,"+[('BUS_ACTIVE',owner_d)]","+[('BUS_ACTIVE',owner_d),('DRIVE_WINDOW',OR('SETUP',AND('DRIVE_WINDOW',NOT('HOLD'))))]")
    s=once(s,"A(active,sram,'WRITE_FLAG',name='DATA_DRIVE')","A(AND(safe,'DRIVE_WINDOW'),sram,'WRITE_FLAG',name='DATA_DRIVE')")
    s=s.replace('NET-12','NET-13A').replace('NET12','NET13A').replace('isa1/net12/','isa1/net13/access/')
    s='# GENERATED by prepare_memory_bus_access.py; original NET-12 is preserved.\n'+s
    builder=ROOT/'tools/build_memory_bus_access.py';builder.write_text(s)
    oldrunner=ROOT/'tools/run_memory_access.py';r=oldrunner.read_text()
    r=r.replace('from build_memory_access import','from build_memory_bus_access import')
    r=r.replace("'tools/build_memory_access.py','tools/run_memory_access.py'","'tools/build_memory_access.py','tools/run_memory_access.py','tools/prepare_memory_bus_access.py','tools/build_memory_bus_access.py','tools/run_memory_bus_control.py'")
    r=r.replace("'verification/net12/memory_access.xml'","'verification/net13/access/memory_access.xml'")
    r=r.replace("'hardware/memory_access/design.json','hardware/memory_access/package-functions.json'","'hardware/memory_bus_access/design.json','hardware/memory_bus_access/package-functions.json'")
    r=r.replace('NET-12','NET-13A')
    runner=ROOT/'tools/run_memory_bus_control.py';runner.write_text('# GENERATED controller compatibility runner; full front-end tested separately.\n'+r)
    out=ROOT/'verification/net13';out.mkdir(parents=True,exist_ok=True)
    paths=[base,oldrunner,Path(__file__),builder,runner]
    (out/'control-origin.json').write_text(json.dumps({'date':'2026-11-25','base':'NET-12 ce19e78eeb865e7787b5f913dd5a6aa6e3914547',
      'transformation':'Separate controller variant adds DRIVE_WINDOW FF in previously spare HC174 channel: set entering ACCESS, clear entering RELEASE. DATA_DRIVE now uses this window; BUS_ACTIVE/VRAM_OWNER retain RELEASE for break-before-make.',
      'files':[{'path':p.relative_to(ROOT).as_posix(),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in paths]},indent=2)+'\n')
    print('Prepared separate bus controller and compatibility runner')


if __name__=='__main__':main()
