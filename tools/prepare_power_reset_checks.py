"""Reproduce separate NET18 digital fixtures from immutable NET16 sources."""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'verification/net18/native'


def main():
    sources = [
        ('sim/net16/tb_reset_domains.sv', 'sim/net18/tb_power_reset.sv'),
        ('sim/net16/tb_reset_apertures.sv', 'sim/net18/tb_power_apertures.sv'),
        ('tools/run_reset_domains.py', 'tools/run_power_reset.py'),
        ('tools/run_reset_apertures.py', 'tools/run_power_apertures.py'),
        ('tools/check_keyboard_500_erc.py', 'tools/check_power_reset_erc.py'),
    ]
    rows, failures = [], []
    for origin, target in sources:
        data = (ROOT / origin).read_text()
        if 'keyboard' in origin:
            data = data.removeprefix('# GENERATED by prepare_keyboard_500_checks.py; predecessors preserved.\n')
            data = data.replace('keyboard_500', 'power_reset').replace('NET-17', 'NET-18')
        else:
            data = data.replace('reset_domains', 'power_reset').replace('reset_apertures', 'power_apertures')
            data = data.replace('sim/net16', 'sim/net18').replace('verification/net16', 'verification/net18')
        data = data.replace('2026-11-25', '2026-11-26')
        data = '// Derived NET18 digital forcepoint fixture; supervisor analog behavior excluded.\n' + data if target.endswith('.sv') else '# GENERATED by prepare_power_reset_checks.py; ancestors unchanged.\n' + data
        path = ROOT / target
        if '--write' in sys.argv:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(data)
        if not path.is_file() or path.read_bytes() != data.encode():
            failures.append(target)
        rows.append({'base': origin, 'base_sha256': hashlib.sha256((ROOT / origin).read_bytes()).hexdigest(),
                     'generated': target, 'generated_sha256': hashlib.sha256(data.encode()).hexdigest()})
    OUT.mkdir(parents=True, exist_ok=True)
    report = {'date': '2026-11-26', 'transformation': 'Namespace/path/date substitutions listed by this source; original reset monitors preserved. RAW_SAFE_N is supervisor forcepoint, not analog model', 'files': rows, 'failures': failures}
    (OUT / ('check-origin.json' if '--write' in sys.argv else 'preparation-check.json')).write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps({'prepared': len(rows), 'failures': failures}))
    return int(bool(failures))


if __name__ == '__main__':
    raise SystemExit(main())
