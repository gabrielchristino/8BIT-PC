"""NET-15 compatibility tests derived from preserved NET-13 controller tests."""
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def main():
    base=ROOT/'sim/net12/tb_memory_access.sv';bench=ROOT/'sim/net15/tb_keyboard_access.sv'
    s=base.read_text().replace('memory_access_netlist','keyboard_access_netlist')
    s=s.replace('.vram_slot(slot)',".vram_slot(slot),.key_ready(1'b1),.io_col_lo(1'b0),.io_col_hi(1'b0)")
    bench.write_text(s)
    old=ROOT/'tools/run_memory_bus_control.py';r=old.read_text()
    r=r.replace('from build_memory_bus_access','from build_keyboard_access')
    r=r.replace("source=OUT/'memory_access_netlist.sv';bench=ROOT/'sim/net12/tb_memory_access.sv'","source=OUT/'keyboard_access_netlist.sv';bench=ROOT/'sim/net15/tb_keyboard_access.sv'")
    r=r.replace("original=VERIFY/'memory_access.xml'","original=VERIFY/'keyboard_access.xml'")
    r=r.replace("'iteration':'NET-13A'","'iteration':'NET-15A'")
    r=r.replace("'tools/build_memory_access.py',","'tools/build_keyboard_access.py','tools/run_keyboard_access_control.py','tools/prepare_keyboard_access_checks.py','verification/net15/access/keyboard_access.xml','tools/build_memory_access.py',")
    r=r.replace('Pin-derived controller and NET-11 decoder;','Extended controller compatibility with KEY_READY tied high and column selects tied low; key waiting tested separately; NET-11 decoder;')
    target=ROOT/'tools/run_keyboard_access_control.py';target.write_text('# GENERATED by prepare_keyboard_access_checks.py; predecessors preserved.\n'+r)
    out=ROOT/'verification/net15/access/check-origin.json'
    out.write_text(json.dumps({'date':'2026-11-25','transformation':'Same three configurations and negative pin tests as NET-13 controller, renamed native graph with KEY_READY=1 and column flags=0 for compatibility. Settling-specific behavior has a separate unit bench.',
      'files':[{'path':p.relative_to(ROOT).as_posix(),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in [base,bench,old,target,Path(__file__)] ]},indent=2)+'\n')
    print('Prepared compatibility tests for extended keyboard access controller')


if __name__=='__main__':main()
