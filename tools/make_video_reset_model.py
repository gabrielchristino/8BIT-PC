"""Separate verification-boundary variant for the external async reset pins.

Keep strict NET-14B package/netlist files intact. Model first-stage recovery
events as either immediate or one-cycle-late binary resolution. This is bounded
digital verification, never an analog metastability/MTBF guarantee.
"""
import hashlib
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]


def main():
    base=ROOT/'sim/net14b/package_models.sv';s=base.read_text()
    old='parameter TIMED=0,EARLY=0'
    assert s.count(old)==1
    s=s.replace(old,'parameter TIMED=0,EARLY=0,RESET_BOUNDARY=0,FIRST_STAGE=0,RESOLVE_LATE=1')
    s=s.replace(' localparam realtime CQ=', ' integer recovery_events=0;\n localparam realtime CQ=',1)
    old='''     if(TIMED && checks && $realtime-released<3)$fatal(1,"AHC74 reset recovery violation %m");
     if(TIMED && checks && $realtime-changed<5)$fatal(1,"AHC74 setup violation %m");
     edge_at=$realtime;q<=#CQ d;'''
    new='''     if(TIMED && checks && $realtime-released<3 && !RESET_BOUNDARY)
       $fatal(1,"AHC74 reset recovery violation %m");
     if(TIMED && checks && $realtime-changed<5)$fatal(1,"AHC74 setup violation %m");
     edge_at=$realtime;
     if(TIMED && checks && $realtime-released<3 && RESET_BOUNDARY)begin
       recovery_events=recovery_events+1;
       // Deliberate abstraction at the external asynchronous boundary only.
       // Never claim that real metastability is bounded by one cycle.
       if(FIRST_STAGE && RESOLVE_LATE)q<=#CQ 0;else q<=#CQ d;
     end else q<=#CQ d;'''
    assert s.count(old)==1;s=s.replace(old,new)
    target=ROOT/'sim/net14c/package_models_async.sv';target.write_text('// GENERATED bounded external reset model; strict predecessor preserved.\n'+s)
    original=ROOT/'hardware/video_system/video_system_netlist.sv';n=original.read_text()
    n=n.replace('parameter TIMED=0,EARLY_CAPTURE=0','parameter TIMED=0,EARLY_CAPTURE=0,RESOLVE_LATE=1')
    references={};lines=[]
    for line in n.splitlines():
        if line.startswith('net14b_ahc74 '):
            match=re.search(r'\) (U\d+_[01])\((.*)\);',line)
            q=match.group(2).split(',')[4]
            if q in ('n_RESET_STAGE1','n_LOCAL_RESET_N'):
                first=q=='n_RESET_STAGE1';ref=match.group(1);references['stage1' if first else 'stage2']=ref
                line=line.replace('.TIMED(TIMED),',f'.TIMED(TIMED),.RESET_BOUNDARY(1),.FIRST_STAGE({int(first)}),.RESOLVE_LATE(RESOLVE_LATE),',1)
        lines.append(line)
    assert len(references)==2
    net=ROOT/'sim/net14c/video_raster_async_netlist.sv';net.write_text('\n'.join(lines)+'\n')
    runner_base=ROOT/'tools/run_video_cpu.py';r=runner_base.read_text()
    r=r.replace("'sim/net14b/package_models.sv','hardware/video_system/video_system_netlist.sv'","'sim/net14c/package_models_async.sv','sim/net14c/video_raster_async_netlist.sv'")
    r=r.replace("'tools/make_video_cpu.py',","'tools/make_video_reset_model.py','tools/run_video_cpu_async.py','sim/net14b/package_models.sv','hardware/video_system/video_system_netlist.sv','tools/make_video_cpu.py',")
    r=r.replace("'results-timed.json' if timed else 'results-ideal.json'","'results-timed-async.json' if timed else 'results-ideal-async.json'")
    r=r.replace('no analog/PVT/PCB signoff','bounded binary reset resolution at external synchronizer only, no analog metastability/MTBF/PVT/PCB signoff')
    print_line='$display("RESET_BOUNDARY stage1_recovery_events=%0d stage2_recovery_events=%0d binary_resolution_late=1 analog_metastability_approved=0",memory.raster.'+references['stage1']+'.recovery_events,memory.raster.'+references['stage2']+'.recovery_events);'
    marker='fixture_defaults=%0d",memory.ram_writes,memory.vram_writes,memory.ram_aborts,memory.vram_aborts,memory.FIXTURE_DEFAULTS);$finish;'
    assert r.count(marker)==1;r=r.replace(marker,marker.replace('$finish;',print_line+'$finish;'))
    runner=ROOT/'tools/run_video_cpu_async.py';runner.write_text('# GENERATED by make_video_reset_model.py; asynchronous boundary abstraction explicit.\n'+r)
    paths=[base,original,runner_base,Path(__file__),target,net,runner]
    out=ROOT/'verification/net14c/reset-model-origin.json'
    out.write_text(json.dumps({'date':'2026-11-25','transformation':'Same pin graph; mark only two external asynchronous reset synchronizer FFs as verification boundaries, count recovery events and test bounded binary resolution. All downstream recovery monitors stay strict. Strict model and its failed integration report remain preserved.','limitations':'One-cycle binary resolution is an assumption, not a vendor guarantee or MTBF proof.','references':references,'files':[{'path':p.relative_to(ROOT).as_posix(),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in paths]},indent=2)+'\n')
    print('Generated separate bounded asynchronous-reset verification model')


if __name__=='__main__':main()
