"""Integrate the two native request clock pin changes without altering ancestors."""
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'verification/net24'


def once(text,old,new):
    assert text.count(old)==1,old
    return text.replace(old,new)


def main():
    paths=[Path(__file__)]
    ancestor=ROOT/'sim/net23/isa1_clocked_memory.sv'
    wrapper=ROOT/'sim/net24/isa1_memory_common_request.sv'
    wrapper.write_text('// GENERATED: only native controller clock regrouping changes.\n'+
                       once(ancestor.read_text(),'system_access_netlist #','common_request_netlist #'))
    paths += [ancestor,wrapper]

    def adapt(source_name,target_name):
        source=ROOT/'tools'/source_name
        text=source.read_text().replace('verification/net23','verification/net24')
        text=text.replace('sim/net23/isa1_clocked_memory.sv','sim/net24/isa1_memory_common_request.sv')
        # Imported MODELS is inherited from NET19. Replace that one native
        # controller input; all CPU/memory/keyboard/source package inputs stay.
        needle='[p for p in '
        assert text.count(needle)==1
        text=text.replace(needle,"[('hardware/common_request/common_request_netlist.sv' if p=='hardware/system_access/system_access_netlist.sv' else p) for p in ")
        text=text.replace('tools/'+source_name,'tools/'+target_name)
        text=text.replace('tools/prepare_clocked_cpu.py','tools/prepare_common_request_checks.py')
        text=text.replace('tools/prepare_clocked_vectors.py','tools/prepare_common_request_checks.py')
        text=text.replace('tools/prepare_common_cpu_checks.py','tools/prepare_common_request_checks.py')
        # Every result includes the native changed graph and builder.
        text=text.replace('verification/net24/native/clocked_reset.xml','verification/net23/native/clocked_reset.xml')
        text=text.replace("'tools/build_clocked_reset.py'",
                          "'tools/build_clocked_reset.py', 'tools/build_common_request.py', 'verification/net24/native/common_request.xml'")
        target=ROOT/'tools'/target_name
        return source,target,text

    source,target,text=adapt('run_clocked_cpu_fault.py','run_common_request_cpu_fault.py')
    # Original fault source bench uses only CPU/memory interfaces, so remains
    # the exact NET23 fixture and is already listed among tested sources.
    target.write_text('# GENERATED by prepare_common_request_checks.py.\n'+text)
    paths += [source,target]

    source,target,text=adapt('run_clocked_vectors.py','run_common_request_vectors.py')
    text=once(text,"text = text.replace('isa1_memory #', 'isa1_clocked_memory #')",
              "text = text.replace('isa1_memory ', 'isa1_clocked_memory ')")
    target.write_text('# GENERATED by prepare_common_request_checks.py; both ideal/parameterized forms.\n'+text)
    paths += [source,target]

    # Full ideal boot/frame begins from the preserved NET22 program fixture,
    # then replaces its external clocks with NET23 configured source outputs.
    source=ROOT/'tools/run_common_program.py'
    text=source.read_text().replace('verification/net22/program','verification/net24/program')
    text=text.replace('hardware/schmitt_reset/schmitt_reset_netlist.sv',"hardware/clocked_reset/clocked_reset_netlist.sv', 'sim/net23/clock_models.sv")
    text=text.replace('sim/net22/isa1_memory_video_common.sv','sim/net24/isa1_memory_common_request.sv')
    text=once(text,'[p for p in base.MODELS',"[('hardware/common_request/common_request_netlist.sv' if p=='hardware/system_access/system_access_netlist.sv' else p) for p in base.MODELS")
    new='''        text = text.replace('isa1_memory ', 'isa1_clocked_memory ')
        old = 'memory(clk,video_clk,reset_n,power_good,'
        assert text.count(old)==1
        text = text.replace(old, 'memory(reset_n,power_good,power_good,')
        old = 'reg clk=0,video_clk=0,reset_n=0,power_good=1,run=0;'
        assert text.count(old)==1
        text = text.replace(old, 'reg reset_n=0,power_good=1,run=0;\\n wire clk=memory.cpu_source,video_clk=memory.master_source;')
        old = ' always #CPU_HALF clk=~clk;always #VIDEO_HALF video_clk=~video_clk;'
        assert text.count(old)==1
        text = text.replace(old, '')
        old = 'module tb_rtl_program;'
        assert text.count(old)==1
        text = text.replace(old, old+'\\n defparam memory.reset_domains.CPU_PERIOD_NS=2*CPU_HALF, memory.reset_domains.MASTER_PERIOD_NS=2*VIDEO_HALF, memory.reset_domains.CPU_STARTUP_NS=100, memory.reset_domains.MASTER_STARTUP_NS=100;')
        return text'''
    text=once(text,'        return text',new)
    text=text.replace('tools/run_common_program.py','tools/run_common_request_program.py').replace('tools/prepare_common_cpu_checks.py','tools/prepare_common_request_checks.py')
    text=text.replace("'tools/build_schmitt_reset.py', 'verification/net21/native/schmitt_reset.xml'",
                      "'tools/build_clocked_reset.py', 'verification/net23/native/clocked_reset.xml', 'tools/build_common_request.py', 'verification/net24/native/common_request.xml'")
    text=text.replace('Full ideal boot/frame with initially unknown SRAM through native reset domains. Analog supervisor, physical clocks/PVT/skew and timed full program not qualified.',
                      'Full ideal boot/frame through native common-request controller and configured source outputs with scaled periods/startup, initially unknown SRAM. No analog oscillator, jitter/POR/MTBF/PVT or timed full program qualification.')
    # Wall-clock allowance only; all simulator assertions and sim deadlines stay.
    text=once(text,'    result = base.main()', '''    original_run = base.run
    def run(command, work, timeout=1200):
        return original_run(command, work, timeout=1800 if command[0]=='vvp' else timeout)
    base.run = run
    result = base.main()''')
    target=ROOT/'tools/run_common_request_program.py'
    target.write_text('# GENERATED by prepare_common_request_checks.py.\n'+text)
    paths += [source,target]
    (OUT/'cpu-adapter-origin.json').write_text(json.dumps({'date':'2026-11-26',
        'transformation':'Only native request controller variant replaces NET19 controller. Other native modules/ROMs preserved. Source-driven CPU write/vector fixtures; program fixture uses explicit scaled oscillator periods and100ns startup, no SRAM seeds. Program wall-clock allowance1800s changes no simulated deadline/assertion.',
        'files':[{'path':p.relative_to(ROOT).as_posix(),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in paths]},indent=2)+'\n')
    print('Prepared controller-regrouping CPU/vector/full-program checks')


if __name__=='__main__':main()
