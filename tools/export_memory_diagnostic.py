"""Preserve the exact main-EEPROM image accepted by NET-13, not a release."""
import hashlib
import json
from pathlib import Path
import tempfile
from run_rtl import ROOT,program_fixture


def main():
    accepted=json.loads((ROOT/'verification/net13/cpu/results-ideal.json').read_text())
    assert not accepted['quick'] and accepted['runs'][-1]['frame_matches_reference']
    assert 'fixture_defaults=0' in accepted['runs'][-1]['execution']['stdout']
    with tempfile.TemporaryDirectory(prefix='isa1-eeprom-export-') as tmp:
        work=Path(tmp);meta,_,_=program_fixture(work)
        data=bytes(int(s,16) for s in (work/'rom_image.hex').read_text().split())
    assert len(data)==32768
    sha=hashlib.sha256(data).hexdigest()
    assert sha==accepted['program']['boot_image_sha256']==meta['boot_image_sha256']
    out=ROOT/'firmware/net13';out.mkdir(parents=True,exist_ok=True)
    binary=out/'integration-diagnostic-eeprom.bin';binary.write_bytes(data)
    hexdump=out/'integration-diagnostic-eeprom.hex';hexdump.write_text(''.join(f'{b:02x}\n' for b in data))
    sources=[Path(__file__),ROOT/'tools/run_rtl.py',ROOT/'firmware/rtl01_diagnostic.asm',ROOT/'verification/net13/cpu/results-ideal.json']
    report={'date':'2026-11-25','origin':'New integration diagnostic generated by preserved RTL-01 fixture builder, exported after NET-13 accepted full boot with unknown unseeded SRAM',
      'format':'32768 raw bytes, physical EEPROM offsets 0000..7FFF; HEX is one byte per line for $readmemh, not Intel HEX',
      'sources':[{'path':p.relative_to(ROOT).as_posix(),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in sources],
      'files':[{'path':p.relative_to(ROOT).as_posix(),'bytes':p.stat().st_size,'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in [binary,hexdump]],
      'not_recovered_original':'Does not replace missing revisions/rev983/diagnostic.asm',
      'production_release':False}
    (out/'origin.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps({'bytes':len(data),'sha256':sha,'production_release':False}))


if __name__=='__main__':main()
