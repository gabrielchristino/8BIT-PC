"""Derive a simulation memory adapter and runner without editing NET-10/RTL-01."""
import hashlib
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]


def replace_once(text,old,new):
    if text.count(old)!=1:raise ValueError('Unexpected base for '+old[:60])
    return text.replace(old,new)


def main():
    source=ROOT/'sim/rtl/isa1_memory.sv';text=source.read_text()
    text=replace_once(text,'module isa1_memory (','module isa1_memory #(parameter TIMED=0) (')
    text=replace_once(text,'// Simulation-only memory/MMIO and VGA arbitration. No physical memory timing.',
      '// NET-11: physical pin-derived address decode; storage/MMIO/CDC/arbitration remain simulation models.')
    old="""         if(boot && address<16'h4000)begin kind<=2;physical<=address;end
         else if(address<16'h8000)begin kind<=0;physical<=address;end
         else if(address<16'ha000)begin kind<=1;physical<={vb,address[12:0]};end
         else if(address<16'hc000)begin kind<=3;physical<=address;end
         else begin kind<=2;physical<={eb,address[13:0]};end"""
    new="""         case(region_select)
           4'b0001:begin kind<=0;physical<=ram_address;end
           4'b0010:begin kind<=1;physical<=vram_address;end
           4'b0100:begin kind<=2;physical<=rom_address;end
           4'b1000:begin kind<=3;physical<=address;end
           default:$fatal(1,"NET11 address decode not settled at capture");
         endcase"""
    text=replace_once(text,old,new)
    text=replace_once(text,' wire safe=reset_n && power_good;',
      ''' wire safe=reset_n && power_good;
 wire [3:0] region_select;wire [5:0] decoded_io;
 wire [14:0] ram_address,vram_address,rom_address;
 memory_decode_netlist #(.TIMED(TIMED)) address_decoder(address,boot,eb,vb,request,safe,
    region_select,decoded_io,ram_address,vram_address,rom_address);''')
    dest=ROOT/'sim/net11/isa1_memory_decode.sv';dest.parent.mkdir(parents=True,exist_ok=True);dest.write_text(text)
    runner=ROOT/'tools/run_cpu_global.py';s=runner.read_text()
    s=replace_once(s,"OUT=ROOT/'verification/net10'","OUT=ROOT/'verification/net11/cpu'")
    s=replace_once(s,"'iteration':'NET-10'","'iteration':'NET-11'")
    s=replace_once(s,"'sim/rtl/isa1_memory.sv'","'hardware/memory_decode/memory_decode_netlist.sv','sim/net11/isa1_memory_decode.sv'")
    s=replace_once(s,"'tools/run_cpu_global.py'","'tools/run_cpu_global.py','tools/make_memory_decode_cpu.py','tools/run_memory_decode_cpu.py','tools/build_memory_decode.py','hardware/memory_decode/design.json','hardware/memory_decode/package-functions.json','verification/net11/memory_decode.xml'")
    s=replace_once(s,"        text=text.replace(' isa1_cpu dut(', ' isa1_cpu #(.TIMED(1)) dut(')","        text=text.replace(' isa1_cpu dut(', ' isa1_cpu #(.TIMED(1)) dut(')\n        text=text.replace('isa1_memory memory(', 'isa1_memory #(.TIMED(1)) memory(')")
    s=replace_once(s,"Joined CPU only; delayed scenario uses scaled slow CPU/video stimuli, not physical VGA timing or full PVT signoff",
      "Joined CPU with pin-derived address decode; storage/MMIO/CDC/video remain behavioral; no physical memory or VGA signoff")
    s='''# GENERATED by tools/make_memory_decode_cpu.py from NET-10 runner.
'''+s
    target=ROOT/'tools/run_memory_decode_cpu.py';target.write_text(s)
    out=ROOT/'verification/net11/cpu';out.mkdir(parents=True,exist_ok=True)
    paths=[source,runner,Path(__file__),dest,target]
    (ROOT/'verification/net11/adapter-origin.json').write_text(json.dumps({'date':'2026-11-25','transformation':'Preserved RTL-01 simulation memory with capture decode replaced by NET-11 pin graph; runner derived from NET-10; no physical storage/access-strobe claim',
      'files':[{'path':p.relative_to(ROOT).as_posix(),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in paths]},indent=2)+'\n')
    print('Generated memory-decode integration adapter and separate runner')


if __name__=='__main__':main()
