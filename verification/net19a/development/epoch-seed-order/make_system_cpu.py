"""Generate the corrected native-controller integration and separate runners."""
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'verification/net19a'


def once(text,old,new):
    if text.count(old)!=1:raise ValueError('Unexpected predecessor '+old[:80])
    return text.replace(old,new)


def main():
    old_memory=ROOT/'sim/net19a/isa1_memory_keyboard.sv'
    text=old_memory.read_text()
    text=once(text,'TIMED=0,FIXTURE_DEFAULTS=1','TIMED=0,FIXTURE_DEFAULTS=1,CONTROL_EARLY=0')
    text=once(text,'keyboard_access_netlist #(.TIMED(TIMED))','system_access_netlist #(.TIMED(TIMED),.EARLY(CONTROL_EARLY))')
    text=text.replace('MMIO is still the preserved logical peripheral.','MMIO and its readiness now come from the native peripheral.')
    memory=ROOT/'sim/net19a/isa1_memory_system.sv';memory.write_text(text)
    old_runner=ROOT/'tools/run_keyboard_cpu.py';r=old_runner.read_text()
    r=r.replace("'hardware/keyboard_access/keyboard_access_netlist.sv'","'sim/net19a/package_models.sv','hardware/system_access/system_access_netlist.sv'")
    r=r.replace("'sim/net19a/isa1_memory_keyboard.sv'","'sim/net19a/isa1_memory_system.sv'")
    r=r.replace("'tools/run_keyboard_cpu.py'","'tools/run_system_cpu.py','tools/make_system_cpu.py','tools/run_keyboard_cpu.py'")
    r=r.replace("'hardware/keyboard_access/design.json'","'hardware/keyboard_access/design.json','hardware/system_access/design.json','verification/net19a/native/system_access.xml','tools/build_system_access.py','references/ti/sn74ahc174.pdf'")
    old="    return text\n"
    new=r'''    # Peripheral FF seeds must settle while ACTIVE=0, off its sampling edge.
    # Return to a CPU falling edge before the remaining CPU register seeds.
    # Direct seed assignments are verification setup, not physical IO writes.
    def stage_banks(match):
        return '@(negedge memory.backend_clk);#0.01;\n     '+match[0]+'\n     @(negedge clk);\n     '
    text=re.sub(r'(?:memory\.peripheral\.U1\.q\[[^\]]+\]=[^;]+;\s*)+',stage_banks,text)
    return text
'''
    r=once(r,old,new)
    r=once(r,"parser.add_argument('--timed', action='store_true')","parser.add_argument('--timed', action='store_true')\n    parser.add_argument('--early', action='store_true')")
    r=r.replace("'bench': bench, 'timed': args.timed", "'bench': bench, 'early_state_cq': args.early, 'timed': args.timed")
    r=r.replace("target = OUT / (args.bench +", "target = OUT / ('system-' + args.bench + ('-early' if args.early else '') +")
    r=r.replace("        text = fixture(original, args.timed, refs)\n", "        text = fixture(original, args.timed, refs)\n        if args.early:text=text.replace('isa1_memory #(.TIMED(1)', 'isa1_memory #(.TIMED(1),.CONTROL_EARLY(1)')\n")
    r=r.replace("(OUT / (bench +", "(OUT / ('system-' + bench + ('-early' if args.early else '') +")
    r=r.replace("OUT / 'frame-ideal.png'", "OUT / 'frame-system-ideal.png'")
    r=r.replace('CPU/raster/memory/native MMIO/keyboard digital integration;', 'CPU/raster/memory/native MMIO/keyboard with three AHC174 controller state packages and off-edge fixture bank seeds;')
    runner=ROOT/'tools/run_system_cpu.py';runner.write_text('# GENERATED by make_system_cpu.py; initial failing integration preserved.\n'+r)
    old_scan=ROOT/'tools/run_keyboard_scan.py';scan=old_scan.read_text().replace('from run_keyboard_cpu import MODELS','from run_system_cpu import MODELS')
    scan=scan.replace("'tools/run_keyboard_cpu.py'","'tools/run_system_cpu.py','tools/make_system_cpu.py','references/ti/sn74ahc174.pdf'")
    scan=scan.replace("'tools/run_keyboard_scan.py'","'tools/run_system_scan.py','tools/run_keyboard_scan.py'")
    scan=scan.replace("'scan-'", "'system-scan-'").replace("'keyboard-scan-eeprom.bin'","'system-keyboard-scan-eeprom.bin'")
    scan_runner=ROOT/'tools/run_system_scan.py';scan_runner.write_text('# GENERATED by make_system_cpu.py; initial scanner preserved.\n'+scan)
    paths=[Path(__file__),old_memory,old_runner,old_scan,memory,runner,scan_runner]
    OUT.mkdir(parents=True,exist_ok=True)
    (OUT/'system-adapter-origin.json').write_text(json.dumps({'date':'2026-11-26','transformation':'Separate native controller with physical AHC174 state packages; same MMIO wiring, corrected off-edge bank seed scheduling in vector fixtures. Program/scan firmware never seed CPU/MMIO/SRAM state. Original failing integration retained. Reset remains predecessor stimulus, not NET18 power domains.',
        'files':[{'path':p.relative_to(ROOT).as_posix(),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in paths]},indent=2)+'\n')
    print('Generated corrected native-controller integration and separate CPU/scan runners')
    return 0


if __name__=='__main__':raise SystemExit(main())
