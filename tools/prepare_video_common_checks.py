"""Prepare separate native raster checks and bounded reset projection for NET22."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'verification/net22'


def once(text, old, new):
    if text.count(old) != 1:
        raise ValueError('Unexpected predecessor ' + old)
    return text.replace(old, new)


def main():
    native = ROOT / 'hardware/video_common_clock/video_common_clock_netlist.sv'
    text = native.read_text()
    text = once(text, 'EARLY_CAPTURE=0)', 'EARLY_CAPTURE=0,RESOLVE_LATE=1)')
    for index in range(2):
        old = f'#(.TIMED(TIMED),.EARLY(0 && EARLY_CAPTURE)) U8_{index}'
        new = f'#(.TIMED(TIMED),.RESET_BOUNDARY(1),.FIRST_STAGE({1 if index == 0 else 0}),.RESOLVE_LATE(RESOLVE_LATE),.EARLY(0 && EARLY_CAPTURE)) U8_{index}'
        text = once(text, old, new)
    destination = ROOT / 'sim/net22/video_common_async_netlist.sv'
    destination.write_text(text)
    bench_source = ROOT / 'sim/net14c/tb_video_system.sv'
    bench = bench_source.read_text().replace('video_system_netlist', 'video_common_clock_netlist')
    bench_path = ROOT / 'sim/net22/tb_video_common.sv'
    bench_path.write_text(bench)
    runner_source = ROOT / 'tools/run_video_system.py'
    runner = runner_source.read_text()
    replacements = [
        ('verification/net14c/native', 'verification/net22/native'),
        ('sim/net14b/package_models.sv', 'sim/net14c/package_models_async.sv'),
        ('hardware/video_system/video_system_netlist.sv', 'sim/net22/phase_packages.sv\',\'sim/net22/video_common_async_netlist.sv'),
        ('sim/net14c/tb_video_system.sv', 'sim/net22/tb_video_common.sv'),
        ('tools/build_video_system.py', 'tools/build_video_common_clock.py'),
        ('tools/run_video_system.py', 'tools/run_video_common.py'),
        ('tools/prepare_video_system_checks.py', 'tools/prepare_video_common_checks.py'),
        ('verification/net14c/native/video_system.xml', 'verification/net22/native/video_common_clock.xml'),
        ('NET-14C', 'NET-22V'),
    ]
    for old, new in replacements:
        runner = runner.replace(old, new)
    # The XML replacement follows the changed verification prefix above.
    runner = runner.replace('verification/net22/native/video_system.xml', 'verification/net22/native/video_common_clock.xml')
    runner_path = ROOT / 'tools/run_video_common.py'
    runner_path.write_text('# GENERATED by prepare_video_common_checks.py; ancestors unchanged.\n' + runner)
    paths = [Path(__file__), native, destination, bench_source, bench_path, runner_source, runner_path]
    (OUT / 'adapter-origin.json').write_text(json.dumps({'date': '2026-11-26',
        'transformation': 'Use native common-clock video variant; mark only reset synchronizer U8 as bounded binary boundary, preserve all downstream monitors; same full-frame memory/controller bench. Phase model from SCAS970 is a separate input.',
        'files': [{'path': p.relative_to(ROOT).as_posix(), 'sha256': hashlib.sha256(p.read_bytes()).hexdigest()} for p in paths]}, indent=2) + '\n')
    print('Prepared separate native common-clock raster checks')


if __name__ == '__main__':
    main()
