"""Derive separate NET20 hold-up/ERC tools; never overwrite their ancestors."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    transforms = [
        ('tools/run_power_hold_up.py', 'tools/run_system_hold_up.py', [
            ("verification/net18", "verification/net20"), ('NET18', 'NET20'),
            ("'max_bank_assert_after_raw_s':19.1e-6", "'max_bank_assert_after_raw_s':20e-6"),
            ('bank=we+19.1e-6', 'bank=we+20e-6'),
            ("sources=['tools/run_power_hold_up.py'", "sources=['tools/run_system_hold_up.py','tools/run_power_hold_up.py','tools/prepare_reset_checks.py'"),
            ("'status':'Conditional engineering budgets.", "'supervisor_output_load_qualified':False,'status':'Conditional engineering budgets; AHC125 input max10pF leaves no trace allowance in supervisor CL10pF test condition. That interface is NOT qualified."),
        ]),
        ('tools/check_power_reset_erc.py', 'tools/check_system_reset_erc.py', [
            ('prepare_power_reset_checks.py', 'prepare_reset_checks.py'),
            ('NET-18', 'NET-20'), ('power_reset', 'system_reset'),
        ]),
    ]
    records = []
    for source, target, changes in transforms:
        text = (ROOT / source).read_text()
        for old, new in changes:
            if old not in text:
                raise ValueError('Missing predecessor fragment ' + old)
            text = text.replace(old, new)
        (ROOT / target).write_text('# GENERATED by prepare_reset_checks.py; ancestors unchanged.\n' + text)
        records.append({'source': source, 'source_sha256': hashlib.sha256((ROOT / source).read_bytes()).hexdigest(),
                        'target': target, 'target_sha256': hashlib.sha256((ROOT / target).read_bytes()).hexdigest()})
    folder = ROOT / 'verification/net20'
    folder.mkdir(parents=True, exist_ok=True)
    (folder / 'check-origin.json').write_text(json.dumps({'date': '2026-11-26', 'transformations': records,
        'scope': 'Extend bank settling budget to 20us after RAW for additional bank/decoder buffer. Same conditional capacitor/current/reverse envelope. Native ERC has no waivers.'}, indent=2) + '\n')
    print('Prepared separate NET20 hold-up and ERC tools')


if __name__ == '__main__':
    main()
