"""Reproduce the separate NET-17 fixtures from recorded transformations."""
import hashlib
import json
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1];OUT=ROOT/'verification/net17/native'
def digest(b):return hashlib.sha256(b).hexdigest()
def main():
    origin=json.loads((OUT/'check-origin.json').read_text());failures=[]
    for row in origin['files']:
        base=ROOT/row['base'];target=ROOT/row['generated']
        if digest(base.read_bytes())!=row['base_sha256']:failures.append('Changed base '+row['base']);continue
        text=base.read_text()
        for old,new in row['replacements']:
            if old not in text:raise ValueError('Missing transformation '+old)
            text=text.replace(old,new)
        if target.name=='run_keyboard_500.py':
            text=text.replace("for case,ref,pin,net_name,expected in [('Connector rows/columns exchanged'","for case,ref,pin,net_name,expected in [('Row series resistor bypassed','R21','1','ROW_WIRE_0','Series row wiring R21'),('Connector rows/columns exchanged'")
            text=text.replace('verification/net15/keyboard_500.xml','verification/net17/native/keyboard_500.xml')
        if target.name=='run_key_settle_500.py':text=text.replace('tb_key_settle_500_500.sv','tb_key_settle_500.sv')
        if target.name in ('run_keyboard_500.py','run_key_settle_500.py'):text=text.replace('sim/net14b/package_models.sv','sim/net14c/package_models_async.sv')
        if target.name=='tb_key_settle_500.sv':
            for old,new in [('quiet_since<1000000','quiet_since<2000000'),('less than 1ms','less than 2ms'),('cycles>9000','cycles>18000'),('cycles<8000','cycles<16000'),('#10000000;','#20000000;')]:text=text.replace(old,new)
        data=text.encode()
        if digest(data)!=row['generated_sha256']:failures.append('Generated bytes '+row['generated']);continue
        if '--write' in sys.argv:target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(data)
        if not target.exists() or digest(target.read_bytes())!=row['generated_sha256']:failures.append('Current bytes '+row['generated'])
    report={'date':'2026-11-26','checked':len(origin['files']),'command':['python3','tools/prepare_keyboard_500_checks.py',*sys.argv[1:]],'failures':failures}
    (OUT/'preparation-check.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report));return int(bool(failures))
if __name__=='__main__':raise SystemExit(main())
