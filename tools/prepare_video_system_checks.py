"""Separate NET-14C frame and ERC runners derived from preserved NET-14B."""
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def main():
    base=ROOT/'sim/net14b/tb_video_raster.sv';bench=ROOT/'sim/net14c/tb_video_system.sv'
    bench.write_text(base.read_text().replace('tb_video_raster','tb_video_system').replace('video_raster_netlist','video_system_netlist'))
    runner_base=ROOT/'tools/run_video_raster.py';s=runner_base.read_text()
    s=s.replace("OUT=ROOT/'verification/net14b'","OUT=ROOT/'verification/net14c/native'")
    s=s.replace("'iteration':'NET-14B'","'iteration':'NET-14C'")
    s=s.replace("'hardware/video_raster/video_raster_netlist.sv'","'hardware/video_system/video_system_netlist.sv'")
    s=s.replace("'sim/net14b/tb_video_raster.sv'","'sim/net14c/tb_video_system.sv'")
    s=s.replace('tb_video_raster','tb_video_system')
    s=s.replace("'tools/build_video_raster.py','tools/run_video_raster.py','verification/net14b/video_raster.xml'", "'tools/build_video_system.py','tools/run_video_system.py','tools/prepare_video_system_checks.py','verification/net14c/native/video_system.xml'")
    runner=ROOT/'tools/run_video_system.py';runner.write_text('# GENERATED by prepare_video_system_checks.py; predecessors preserved.\n'+s)
    erc_base=ROOT/'tools/check_video_raster_erc.py';erc=ROOT/'tools/check_video_system_erc.py'
    erc.write_text('# GENERATED by prepare_video_system_checks.py; predecessors preserved.\n'+erc_base.read_text().replace('from build_video_raster','from build_video_system').replace('video_raster','video_system').replace('NET-14B','NET-14C'))
    paths=[base,bench,runner_base,runner,erc_base,erc,Path(__file__)]
    (ROOT/'verification/net14c/native/check-origin.json').write_text(json.dumps({'date':'2026-11-25','transformation':'Same full-frame/negative observation fixture with renamed native variant and output paths; preserve original tests and runners.','files':[{'path':p.relative_to(ROOT).as_posix(),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in paths]},indent=2)+'\n')
    print('Prepared separate native system frame/ERC checks')


if __name__=='__main__':main()
