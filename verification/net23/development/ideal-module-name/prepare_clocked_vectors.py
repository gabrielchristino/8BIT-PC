"""Adapt instruction fixtures to source-driven native clocks, preserving seeds."""
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def main():
    source=ROOT/'tools/run_common_vectors.py'
    text=source.read_text()
    for old,new in [('verification/net22/vectors','verification/net23/vectors'),
                    ('hardware/schmitt_reset/schmitt_reset_netlist.sv','hardware/clocked_reset/clocked_reset_netlist.sv'),
                    ('sim/net22/isa1_memory_video_common.sv',"sim/net23/clock_models.sv', 'sim/net23/isa1_clocked_memory.sv"),
                    ('tools/run_common_vectors.py','tools/run_clocked_vectors.py'),
                    ('tools/prepare_common_cpu_checks.py','tools/prepare_clocked_vectors.py'),
                    ('tools/build_schmitt_reset.py','tools/build_clocked_reset.py'),
                    ('verification/net21/native/schmitt_reset.xml','verification/net23/native/clocked_reset.xml')]:
        text=text.replace(old,new)
    assert text.count('import sys')==1
    text=text.replace('import sys','import sys\nimport re')
    old='        return text'
    assert text.count(old)==1
    new='''        text = text.replace('isa1_memory #', 'isa1_clocked_memory #')
        old = 'memory(clk,video_clk,reset_n,power_good,'
        assert text.count(old)==1
        text = text.replace(old, 'memory(reset_n,power_good,power_good,')
        old = 'reg clk=0,video_clk=0,reset_n=0,power_good=1,run=0;'
        assert text.count(old)==1
        text = text.replace(old, 'reg reset_n=0,power_good=1,run=0;\\n wire clk=memory.cpu_source,video_clk=memory.master_source;')
        text,count = re.subn(r' always #[0-9.]+ clk=~clk;\\n', '', text)
        assert count==1
        text,count = re.subn(r' always #[0-9.]+ video_clk=~video_clk;\\n', '', text)
        assert count==1
        if not timed:
            old = 'module tb_rtl_cpu;'
            assert text.count(old)==1
            text = text.replace(old, old + '\\n defparam memory.reset_domains.CPU_PERIOD_NS=10, memory.reset_domains.MASTER_PERIOD_NS=3.5, memory.reset_domains.CPU_STARTUP_NS=100, memory.reset_domains.MASTER_STARTUP_NS=100;')
        return text'''
    text=text.replace(old,new)
    text=text.replace('Analog supervisor forcepoint/RC conditional; no board/PVT/MTBF signoff.',
                      'Native configured oscillator clocks; qualified oscillator VDD, analog supervisor forcepoint/RC conditional, no jitter/POR/board/PVT/MTBF signoff. Ideal mode explicitly scales oscillator period/startup parameters and is not physical frequency.')
    destination=ROOT/'tools/run_clocked_vectors.py'
    destination.write_text('# GENERATED by prepare_clocked_vectors.py; predecessors unchanged.\n'+text)
    paths=[Path(__file__),source,destination,ROOT/'sim/net23/isa1_clocked_memory.sv']
    (ROOT/'verification/net23/vectors-adapter-origin.json').write_text(json.dumps({'date':'2026-11-26',
        'transformation':'Replace external clock generators with native source outputs, same CPU reset/core CLK and off-edge fixture seed protocol. Timed source defaults100kHz/25.175MHz/start10ms; ideal periods10/3.5ns and start100ns are scaled bench parameters only.',
        'files':[{'path':p.relative_to(ROOT).as_posix(),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in paths]},indent=2)+'\n')
    print('Prepared separate source-clocked instruction fixture')


if __name__=='__main__':main()
