"""Separate memory/CPU adapter driven by native configured source outputs."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'verification/net23'


def once(text, old, new):
    assert text.count(old) == 1, old
    return text.replace(old, new)


def main():
    source = ROOT / 'sim/net22/isa1_memory_video_common.sv'
    text = once(source.read_text(), 'module isa1_memory #', 'module isa1_clocked_memory #')
    text = once(text, 'input wire clk,video_clk,reset_n,power_good,request,write_enable,',
                'input wire reset_n,power_good,osc_power_valid,request,write_enable,')
    text = once(text, 'wire backend_clk;', 'wire backend_clk,cpu_source,master_source;')
    old = ''' schmitt_reset_netlist #(.TIMED(TIMED),.RESOLVE_LATE(RESET_POLICY),
   .ASSERT_DELAY(TIMED?BANK_ASSERT_NS:1),.RELEASE_DELAY(TIMED?42000:4)) reset_domains(
   raw_safe,backend_clk,clk,bank_reset_n,cpu_reset_n,safe,
   bank_memory_n,bank_keyboard_n,bank_decode_n,safe_memory,safe_keyboard,
   cpu_core_clk,access_clk,keyboard_clk);'''
    new = ''' clocked_reset_netlist #(.TIMED(TIMED),.RESOLVE_LATE(RESET_POLICY),
   .ASSERT_DELAY(TIMED?BANK_ASSERT_NS:1),.RELEASE_DELAY(TIMED?42000:4)) reset_domains(
   .raw_safe_n(raw_safe),.backend_source(backend_clk),.osc_power_valid(osc_power_valid),
   .bank_reset_n(bank_reset_n),.cpu_reset_n(cpu_reset_n),.access_safe(safe),
   .bank_memory_n(bank_memory_n),.bank_keyboard_n(bank_keyboard_n),.bank_decode_n(bank_decode_n),
   .safe_memory(safe_memory),.safe_keyboard(safe_keyboard),.cpu_core_clk(cpu_core_clk),
   .access_clk(access_clk),.keyboard_clk(keyboard_clk),.cpu_source(cpu_source),.master_source(master_source));'''
    text = once(text, old, new)
    text = once(text, 'video_clk,reset_n,power_good,pixel_bus,', 'master_source,reset_n,power_good,pixel_bus,')
    destination = ROOT / 'sim/net23/isa1_clocked_memory.sv'
    destination.write_text('// GENERATED: configured native sources; oscillator power validity is a qualified model input.\n' + text)
    ancestor = ROOT / 'sim/net21/tb_schmitt_cpu_fault.sv'
    bench = once(ancestor.read_text(), 'reg clk=0,master=0,raw=1,run=0,monitoring=0,counting=0;',
                 'reg raw=1,run=0,monitoring=0,counting=0;\n wire clk=memory.cpu_source;')
    bench = once(bench, ' always #5000 clk=~clk;\n always #19.860973 master=~master;\n', '')
    bench = once(bench, 'isa1_memory #', 'isa1_clocked_memory #')
    bench = once(bench, "clk,master,raw,1'b1,req,", "raw,1'b1,1'b1,req,")
    bench_path = ROOT / 'sim/net23/tb_clocked_cpu_fault.sv'
    bench_path.write_text('// GENERATED: actual CPU clock and raster come from native sources; no external clock force.\n' + bench)
    runner_source = ROOT / 'tools/run_common_cpu_fault.py'
    runner = runner_source.read_text()
    for old, new in [('verification/net22', 'verification/net23'),
                     ('hardware/schmitt_reset/schmitt_reset_netlist.sv', 'hardware/clocked_reset/clocked_reset_netlist.sv'),
                     ('sim/net22/isa1_memory_video_common.sv', "sim/net23/clock_models.sv', 'sim/net23/isa1_clocked_memory.sv"),
                     ('sim/net21/tb_schmitt_cpu_fault.sv', 'sim/net23/tb_clocked_cpu_fault.sv'),
                     ('tools/run_common_cpu_fault.py', 'tools/run_clocked_cpu_fault.py'),
                     ('tools/build_schmitt_reset.py', 'tools/build_clocked_reset.py'),
                     ('tools/prepare_common_cpu_checks.py', 'tools/prepare_clocked_cpu.py'),
                     ('verification/net21/native/schmitt_reset.xml', 'verification/net23/native/clocked_reset.xml')]:
        runner = runner.replace(old, new)
    runner = runner.replace('Common-clock video; qualified RAW/RC and selected delays, not analog supervisor/PVT/physical approval.',
                            'Native configured oscillators and common-clock video; qualified oscillator VDD kept valid, RAW/RC and selected delays. Not analog supervisor/oscillator/jitter/POR/PVT/physical approval.')
    runner_path = ROOT / 'tools/run_clocked_cpu_fault.py'
    runner_path.write_text('# GENERATED by prepare_clocked_cpu.py.\n' + runner)
    erc_source = ROOT / 'tools/check_video_common_clock_erc.py'
    erc = erc_source.read_text().replace('build_video_common_clock', 'build_clocked_reset').replace('video_common_clock', 'clocked_reset').replace('NET-22V', 'NET-23')
    erc_path = ROOT / 'tools/check_clocked_reset_erc.py'
    erc_path.write_text('# GENERATED by prepare_clocked_cpu.py.\n' + erc)
    paths = [Path(__file__), source, destination, ancestor, bench_path, runner_source, runner_path, erc_source, erc_path]
    (OUT / 'cpu-adapter-origin.json').write_text(json.dumps({'date': '2026-11-26',
        'transformation': 'Remove external CPU/master clock inputs; use native configured source outputs. Distinguish qualified oscillator VDD from supervisor RAW/power_good. CPU clear and independent SRAM pin checks preserved. Fault fixture retains memory epochs across restart.',
        'files': [{'path': p.relative_to(ROOT).as_posix(), 'sha256': hashlib.sha256(p.read_bytes()).hexdigest()} for p in paths]}, indent=2) + '\n')
    print('Prepared separate source-driven CPU/memory adapter and actual write fault checks')


if __name__ == '__main__':
    main()
