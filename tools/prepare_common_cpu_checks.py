"""Separate CPU/keyboard/reset integration for native common-clock video."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'verification/net22'


def main():
    source = ROOT / 'sim/net21/isa1_memory_schmitt.sv'
    text = source.read_text()
    assert text.count('video_system_netlist') == 1
    text = text.replace('video_system_netlist', 'video_common_clock_netlist')
    target = ROOT / 'sim/net22/isa1_memory_video_common.sv'
    target.write_text(text)
    records = []
    for old, new in [
        ('tools/run_schmitt_scan.py', 'tools/run_common_scan.py'),
        ('tools/run_schmitt_memory.py', 'tools/run_common_memory.py'),
        ('tools/run_schmitt_cpu_fault.py', 'tools/run_common_cpu_fault.py'),
        ('tools/run_reset_vectors.py', 'tools/run_common_vectors.py'),
        ('tools/run_reset_program.py', 'tools/run_common_program.py'),
    ]:
        text = (ROOT / old).read_text()
        text = text.replace('verification/net20', 'verification/net22').replace('verification/net21', 'verification/net22')
        for old_path in ['sim/net20/isa1_memory_reset.sv', 'sim/net21/isa1_memory_schmitt.sv']:
            text = text.replace(old_path, 'sim/net22/isa1_memory_video_common.sv')
        text = text.replace('hardware/system_reset/system_reset_netlist.sv', 'hardware/schmitt_reset/schmitt_reset_netlist.sv')
        # Remove the old raster from every derived model list, and append the
        # common-clock projection plus new selected package model exactly once.
        text = text.replace("p != 'sim/net19a/isa1_memory_system.sv'", "p not in ('sim/net19a/isa1_memory_system.sv', 'sim/net14c/video_raster_async_netlist.sv')")
        endpoint = "'hardware/schmitt_reset/schmitt_reset_netlist.sv', 'sim/net22/isa1_memory_video_common.sv'"
        if endpoint not in text:
            raise ValueError('Unexpected model list ' + old)
        text = text.replace(endpoint, endpoint + ", 'sim/net22/phase_packages.sv', 'sim/net22/video_common_async_netlist.sv'")
        text = text.replace(old, new)
        text = text.replace('tools/make_reset_system.py', 'tools/prepare_common_cpu_checks.py')
        text = text.replace('tools/prepare_schmitt_checks.py', 'tools/prepare_common_cpu_checks.py')
        text = text.replace('tools/build_system_reset.py', 'tools/build_schmitt_reset.py')
        text = text.replace('verification/net22/native/system_reset.xml', 'verification/net21/native/schmitt_reset.xml')
        text = text.replace('verification/net22/native/schmitt_reset.xml', 'verification/net21/native/schmitt_reset.xml')
        text = text.replace('Qualified RAW/RC', 'Common-clock video; qualified RAW/RC')
        path = ROOT / new
        path.write_text('# GENERATED by prepare_common_cpu_checks.py; ancestors unchanged.\n' + text)
        records.append({'source': old, 'source_sha256': hashlib.sha256((ROOT / old).read_bytes()).hexdigest(),
                        'target': new, 'target_sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
    old = ROOT / 'tools/check_video_system_erc.py'
    text = old.read_text().replace('video_system', 'video_common_clock').replace('2026-11-25', '2026-11-26').replace('NET-14C', 'NET-22V')
    text = text.replace('prepare_video_system_checks.py', 'prepare_common_cpu_checks.py')
    erc = ROOT / 'tools/check_video_common_clock_erc.py'
    erc.write_text('# GENERATED by prepare_common_cpu_checks.py.\n' + text)
    paths = [Path(__file__), source, target, old, erc]
    (OUT / 'cpu-adapter-origin.json').write_text(json.dumps({'date': '2026-11-26',
        'scope': 'Separate native video phase/counter variant with existing Schmitt/reset/CPU/keyboard and unchanged firmware. Clock source remains explicit bench stimulus, not an oscillator model.',
        'files': [{'path': p.relative_to(ROOT).as_posix(), 'sha256': hashlib.sha256(p.read_bytes()).hexdigest()} for p in paths],
        'transformations': records}, indent=2) + '\n')
    print('Prepared CPU, scan, SRAM safety and partial ERC checks for common-clock video')


if __name__ == '__main__':
    main()
